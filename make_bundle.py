"""
make_bundle.py - run by build_exe.bat before PyInstaller.

Turns config.json (the project list) and ui.html (the page) into _bundled.py, which
PyInstaller compiles into the .exe. People using the .exe then have no .json, .html or
.py files to see or edit - not next to the .exe and not in Windows' temporary folder.

To change the projects: edit config.json in this folder, then run build_exe.bat again.
"""
import json
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CONFIG = os.path.join(HERE, "config.json")
UI = os.path.join(HERE, "ui.html")
OUT = os.path.join(HERE, "_bundled.py")

DEFAULT = {
    "projects": ["Netpay"],
    "tasks": {
        "Create new bulk files": {"extensions": [".xlsx"], "kind": "create"},
        "Update file names / column data": {"extensions": [".xlsx"], "kind": "update"},
    },
}


def main():
    if not os.path.exists(CONFIG):
        # First build with this version: reuse the project list from the old .exe's folder if present.
        old = os.path.join(HERE, "dist", "config.json")
        if os.path.exists(old):
            shutil.copyfile(old, CONFIG)
            print(f"Using the project list from {old}")
        else:
            with open(CONFIG, "w", encoding="utf-8") as f:
                json.dump(DEFAULT, f, indent=2)
            print("Created config.json with the default project list.")
    try:
        with open(CONFIG, "r", encoding="utf-8") as f:
            config = json.load(f)
    except ValueError as e:
        sys.exit(f"config.json is not valid: {e}\nFix it (e.g. a missing comma or quote) and build again.")
    projects = config.get("projects")
    if not isinstance(projects, list) or not projects or not all(isinstance(p, str) and p.strip() for p in projects):
        sys.exit('config.json needs a "projects" list with at least one name, e.g. "projects": ["Netpay"]')
    with open(UI, "r", encoding="utf-8") as f:
        page = f.read()
    with open(OUT, "w", encoding="ascii") as f:
        f.write("# Generated by make_bundle.py at build time. Do not edit: edit config.json / ui.html and build again.\n")
        f.write(f"CONFIG = {ascii(config)}\n")
        f.write(f"UI_HTML = {ascii(page)}\n")
    print(f"Packed into the app: projects {', '.join(projects)}; the page ({len(page):,} characters).")


if __name__ == "__main__":
    main()
